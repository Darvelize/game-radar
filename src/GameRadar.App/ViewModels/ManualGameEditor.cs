using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using GameRadar.Core.Manual;

namespace GameRadar.App.ViewModels;

/// <summary>A choice of the platform list of a game added by hand.</summary>
public sealed record ManualPlatformOption(ManualPlatform Platform, string Label);

/// <summary>A choice of the "how far you went" list of a game added by hand.</summary>
public sealed record ManualLevelOption(ManualLevel Level, string Label);

/// <summary>
/// The lists shared by every game added by hand (the history lines and the
/// "add a game" page). Brand names are not translated.
/// </summary>
public static class ManualGameOptions
{
    public static IReadOnlyList<ManualPlatformOption> Platforms { get; } =
    [
        new(ManualPlatform.PlayStation, "PlayStation"),
        new(ManualPlatform.OldXbox, "Xbox"),
        new(ManualPlatform.Switch, "Nintendo"),
        new(ManualPlatform.OtherPcStore, Strings.ManualPlatform_OtherPcStore),
        new(ManualPlatform.Android, "Android"),
        new(ManualPlatform.Ios, "iOS"),
        new(ManualPlatform.Other, Strings.ManualPlatform_Other)
    ];

    public static IReadOnlyList<ManualLevelOption> Levels { get; } =
    [
        new(ManualLevel.Mastered, Strings.ManualLevel_Mastered),
        new(ManualLevel.Completed, Strings.ManualLevel_Completed),
        new(ManualLevel.PlayedALot, Strings.ManualLevel_PlayedALot),
        new(ManualLevel.PlayedALittle, Strings.ManualLevel_PlayedALittle),
        new(ManualLevel.DidNotLike, Strings.ManualLevel_DidNotLike)
    ];

    public static ManualPlatformOption Of(ManualPlatform platform) => Platforms.First(o => o.Platform == platform);

    public static ManualLevelOption Of(ManualLevel level) => Levels.First(o => o.Level == level);
}

/// <summary>
/// The line of a game added by hand in the history, edited in place: its
/// platform and how far the player went, or removed.
/// </summary>
public sealed partial class ManualGameEditor : ObservableObject
{
    private readonly Action<ManualGame>? _changed;
    private readonly Action<ManualGame> _removed;

    /// <param name="changed">Called with the game as edited (same <see cref="ManualGame.Id"/>).</param>
    /// <param name="removed">Called when the player removes it.</param>
    public ManualGameEditor(ManualGame game, Action<ManualGame> changed, Action<ManualGame> removed)
    {
        Game = game;
        _removed = removed;
        // Initial values set BEFORE storing the callback: building the line
        // must not look like a choice of the player.
        SelectedPlatform = ManualGameOptions.Of(game.Platform);
        SelectedLevel = ManualGameOptions.Of(game.Level);
        _changed = changed;
    }

    public ManualGame Game { get; private set; }

    public IReadOnlyList<ManualPlatformOption> Platforms => ManualGameOptions.Platforms;
    public IReadOnlyList<ManualLevelOption> Levels => ManualGameOptions.Levels;

    [ObservableProperty]
    public partial ManualPlatformOption SelectedPlatform { get; set; }

    [ObservableProperty]
    public partial ManualLevelOption SelectedLevel { get; set; }

    // Hooks generated by the MVVM Toolkit, called after each change (never
    // with null: the views bind these lists through KeepChoice).
    partial void OnSelectedPlatformChanged(ManualPlatformOption value) => Edit(Game with { Platform = value.Platform });

    partial void OnSelectedLevelChanged(ManualLevelOption value) => Edit(Game with { Level = value.Level });

    private void Edit(ManualGame edited)
    {
        if (edited == Game)
            return;
        Game = edited;
        _changed?.Invoke(edited);
    }

    [RelayCommand]
    private void Remove() => _removed(Game);
}
