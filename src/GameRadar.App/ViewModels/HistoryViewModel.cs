using System.Collections.ObjectModel;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using GameRadar.Core.Manual;
using GameRadar.Core.Models;
using GameRadar.Core.Services;
using GameRadar.Core.Steam;

namespace GameRadar.App.ViewModels;

/// <summary>Order of the history list.</summary>
public enum HistorySort
{
    /// <summary>Most recently played first (the order of the histories).</summary>
    Recent,
    Alphabetical
}

// The history page: its rows, the search, the sort and the filters. Sort and
// filters are kept for the session only, like the settings tab: a fresh
// launch shows every game again. Games added by hand are edited in place on
// their line, and weighed in the taste like the synced games.
public sealed partial class HistoryViewModel : ObservableObject
{
    private readonly AccountsViewModel _accounts;
    private readonly LibraryState _library;
    private readonly SettingsSaver _saver;
    private readonly SourceFilterViewModel _filter;
    private readonly Action _choicesChanged;

    /// <param name="filter">Gives the player's plan: the "Game Pass" badge only for the games of their plan.</param>
    /// <param name="choicesChanged">A choice (taste, finished, a game edited) is in the settings: the window saves it and recomputes.</param>
    public HistoryViewModel(
        AccountsViewModel accounts,
        LibraryState library,
        SettingsSaver saver,
        SourceFilterViewModel filter,
        Action choicesChanged)
    {
        _accounts = accounts;
        _library = library;
        _saver = saver;
        _filter = filter;
        _choicesChanged = choicesChanged;
        // Tags found by the recommendations: shown on the rows as they are, no rebuild.
        _library.TagsChanged += ShowTags;
        // Before the sort below: choosing it filters the list.
        Filters = CreateFilters();
        SelectedSort = SortOptions[0];
    }

    /// <summary>False until a history is loaded or a game is added by hand: the welcome screen is shown instead.</summary>
    [ObservableProperty]
    public partial bool HasHistory { get; set; }

    /// <summary>Header of the history page: both platforms together.</summary>
    [ObservableProperty]
    public partial string Summary { get; set; } = string.Empty;

    /// <summary>How many played games (one per platform) the last rebuild started from.</summary>
    public int GameCount { get; private set; }

    // Every history row, built once per data change; Games shows the
    // filtered subset, recomputed at each keystroke without rebuilding rows.
    public List<GameGroupRow> AllRows { get; } = [];

    /// <summary>History rows matching the search, filled in place so the bound list refreshes itself.</summary>
    public ObservableCollection<GameGroupRow> Games { get; } = [];

    [ObservableProperty]
    public partial string SearchText { get; set; } = string.Empty;

    [ObservableProperty]
    public partial string FilterStatus { get; set; } = string.Empty;

    // Hook generated by the MVVM Toolkit: typing refreshes the list.
    partial void OnSearchTextChanged(string value) => Apply();

    /// <summary>A choice of the "Trier" list.</summary>
    public sealed record SortOption(HistorySort Sort, string Label);

    public IReadOnlyList<SortOption> SortOptions { get; } =
    [
        new(HistorySort.Recent, Strings.History_Sort_Recent),
        new(HistorySort.Alphabetical, Strings.History_Sort_Alphabetical)
    ];

    [ObservableProperty]
    public partial SortOption SelectedSort { get; set; }

    // The picklists, in the order of the page: platform, status, taste.
    public IReadOnlyList<HistoryFilterGroup> Filters { get; }

    /// <summary>The first picklist: its boxes are offered only for the platforms present.</summary>
    public HistoryFilterGroup PlatformFilter => Filters[0];

    /// <summary>
    /// The picklists of the history page. A box per synced platform (a new
    /// platform gets one by itself), then the games added by hand.
    /// </summary>
    private IReadOnlyList<HistoryFilterGroup> CreateFilters() =>
    [
        new HistoryFilterGroup(Strings.History_Filter_Platform,
            Strings.History_Filter_AllFeminine, Strings.History_Filter_NoneFeminine, OnFilterChanged,
            [
                .. _accounts.SyncedPlatforms.Select(p => (p.Platform, (Func<GameGroupRow, bool>)(r => r.HasPlatform(p.Platform)))),
                (Strings.History_Filter_Manual, r => r.IsManual)
            ]),
        // A game is in exactly one status box: mastered, else finished, else played.
        new HistoryFilterGroup(Strings.History_Filter_Status,
            Strings.History_Filter_All, Strings.History_Filter_None, OnFilterChanged,
            (Strings.Status_Mastered, r => r.IsMastered),
            (Strings.Status_Completed, r => !r.IsMastered && r.IsStatusHighlighted),
            (Strings.Status_Played, r => !r.IsMastered && !r.IsStatusHighlighted)),
        new HistoryFilterGroup(Strings.History_Filter_Taste,
            Strings.History_Filter_All, Strings.History_Filter_None, OnFilterChanged,
            (Strings.History_Filter_Counting, r => r.CountsInTaste),
            (Strings.History_Filter_Ignored, r => !r.CountsInTaste)),
        // "Sans tags": the games that weigh in the recommendations without any tag
        // (those that do not count are not looked up). Every other game is "Avec tags".
        new HistoryFilterGroup(Strings.History_Filter_Tags,
            Strings.History_Filter_All, Strings.History_Filter_None, OnFilterChanged,
            (Strings.History_Filter_WithTags, r => !r.CountsWithoutTags),
            (Strings.History_Filter_WithoutTags, r => r.CountsWithoutTags))
    ];

    /// <summary>Some box unticked: "Tout afficher" is offered.</summary>
    public bool IsFiltered => Filters.Any(g => g.IsFiltered);

    // Hook generated by the MVVM Toolkit. Only the sort and the boxes refilter
    // the list: ticking a row's heart does not make it vanish under the mouse
    // while "Ignorés" is unticked.
    partial void OnSelectedSortChanged(SortOption value) => Apply();

    // Set while "Tout afficher" ticks every box: the list is refiltered once
    // at the end, not once per box.
    private bool _showingAll;

    private void OnFilterChanged()
    {
        if (_showingAll)
            return;

        OnPropertyChanged(nameof(IsFiltered));
        Apply();
    }

    [RelayCommand]
    private void ShowAll()
    {
        _showingAll = true;
        try
        {
            foreach (var choice in Filters.SelectMany(g => g.Choices))
                choice.IsChecked = true;
        }
        finally
        {
            _showingAll = false;
        }
        OnFilterChanged();
    }

    /// <summary>Refilters and re-sorts the visible rows from the search, the sort and the boxes.</summary>
    /// <param name="keep">Rows shown whatever the boxes say.</param>
    private void Apply(Func<GameGroupRow, bool>? keep = null)
    {
        // Same normalization as the catalog matching: "pokemon" finds "Pokémon™".
        string search = CatalogMatcher.NormalizeName(SearchText);
        var visible = Sort(AllRows
                .Where(r => search.Length == 0 || r.SearchKey.Contains(search, StringComparison.Ordinal))
                .Where(r => Passes(r) || keep?.Invoke(r) == true))
            .ToList();

        Games.Clear();
        foreach (var row in visible)
            Games.Add(row);
        UpdateFilterStatus();
    }

    /// <summary>"298 jeux affichés sur 308", without rebuilding the list.</summary>
    private void UpdateFilterStatus()
    {
        FilterStatus = Localization.Format(Strings.History_Filter, Games.Count, AllRows.Count);
    }

    /// <summary>True when every picklist lets the row through.</summary>
    private bool Passes(GameGroupRow row) => Filters.All(g => g.Passes(row));

    /// <summary>The visible rows in the chosen order.</summary>
    private IEnumerable<GameGroupRow> Sort(IEnumerable<GameGroupRow> rows) =>
        SelectedSort.Sort == HistorySort.Alphabetical
            // The culture's order: "Éternal" next to "Eternal", case ignored.
            ? rows.OrderBy(r => r.Name, StringComparer.Create(System.Globalization.CultureInfo.CurrentCulture, ignoreCase: true))
            : rows;

    /// <summary>Which platform boxes to offer (those with games), after each data change.</summary>
    private void UpdatePlatforms()
    {
        foreach (var choice in PlatformFilter.Choices)
            choice.IsOffered = AllRows.Any(choice.Matches);
    }

    /// <summary>
    /// The rows were rebuilt from the current data: whoever shows figures drawn
    /// from them (the relative times, the Game Pass line) refreshes them.
    /// </summary>
    public event Action? Rebuilt;

    /// <summary>Rebuilds the rows, the filters' platform boxes and the status lines from the current data.</summary>
    public void Rebuild()
    {
        var matcher = CurrentMatcher();
        var games = _library.CombinedHistory();
        GameCount = games.Count;

        AllRows.Clear();
        var now = DateTimeOffset.UtcNow;
        // One row per game: Warframe on Xbox and on Steam is a single row.
        foreach (var group in HistoryMerger.GroupByGame(games))
            AllRows.Add(BuildRow(group, matcher, now));
        UpdatePlatforms();
        Apply();
        UpdateStatus();
        HasHistory = _library.HasAnyHistory;
        Rebuilt?.Invoke();
    }

    /// <summary>Status lines of the platforms, and the history page header.</summary>
    private void UpdateStatus()
    {
        foreach (var platform in _accounts.SyncedPlatforms)
            platform.UpdateStatus();

        int mastered = AllRows.Count(r => r.IsMastered);
        int completed = AllRows.Count(r => r.IsCompleted && r.CanMarkCompleted);
        Summary = AllRows.Count == 0 ? Strings.History_NoGames
            : completed > 0 ? Localization.Format(Strings.History_SummaryCompleted, AllRows.Count, mastered, completed)
            : Localization.Format(Strings.History_Summary, AllRows.Count, mastered);
    }

    private CatalogMatcher? CurrentMatcher() =>
        _library.Catalog is null ? null : new CatalogMatcher(_library.Catalog.Games);

    /// <summary>The history line of one game, on all its platforms.</summary>
    private GameGroupRow BuildRow(IReadOnlyList<PlayedGame> group, CatalogMatcher? matcher, DateTimeOffset now)
    {
        var settings = _saver.Settings;
        // The catalog entry as the player's plan sees it: the "Game Pass"
        // badge only for games of their plan.
        var plan = _filter.GamePassPlan;
        var row = new GameGroupRow(
            group.Select(game => (game, matcher?.Find(game)?.ForPlan(plan))).ToList(),
            settings.ExcludedFromTaste,
            settings.IncludedInTaste,
            settings.MarkedCompleted,
            now,
            OnUserChoiceChanged,
            ManualEditorFor,
            TagEditorFor(GameTitle.Key(group[0].Name)));
        ShowTags(row);
        return row;
    }

    // Its 3 most voted Steam tags, once the recommendations computation shared them.
    private void ShowTags(GameGroupRow row)
    {
        if (_library.Tags is not var (index, names))
            return;
        // One list of choices for every row, rebuilt only when the names change.
        if (!ReferenceEquals(_tagChoices?.Names, names))
            _tagChoices = new SteamTagChoices(names);
        row.ShowTags(index, _tagChoices!);
    }

    private SteamTagChoices? _tagChoices;

    // The rows built before the tags were known (or before new ones were found).
    private void ShowTags()
    {
        foreach (var row in AllRows)
            ShowTags(row);
        // Tags found change what the "Tags" boxes let through: refiltered, but a
        // row shown that the player is tagging stays (no row vanishes under the mouse).
        if (IsFiltered)
        {
            var shown = Games.ToHashSet();
            Apply(keep: r => r.TagEditor.WasEdited && shown.Contains(r));
        }
    }

    /// <summary>
    /// The user ticked or unticked "Compte dans mes goûts" or "Histoire finie"
    /// on a history row: the settings mirror the row's current state, for
    /// each platform of the game.
    /// </summary>
    private void OnUserChoiceChanged(GameGroupRow row)
    {
        var settings = _saver.Settings;
        foreach (var detail in row.Details)
        {
            // Only where the choice means something: a never-launched Steam
            // game marked "finished" would count as a favorite. Unticking
            // clears every platform, so no stale mark is left behind.
            SetMembership(settings.MarkedCompleted, detail.Key, detail.CanMarkCompleted && row.IsCompleted);

            // A choice is stored only where it differs from the rule (barely
            // played games left out): elsewhere the rule decides, so a game
            // counts by itself once the player gets further.
            bool wanted = detail.CanCountInTaste && row.CountsInTaste;
            bool byDefault = detail.CountsByDefault;
            SetMembership(settings.ExcludedFromTaste, detail.Key, detail.CanCountInTaste && !wanted && byDefault);
            SetMembership(settings.IncludedInTaste, detail.Key, wanted && !byDefault);
        }
        UpdateStatus();
        _choicesChanged();
    }

    // ---------- Tags added by the player ----------

    /// <summary>The tags editor of a game (title key: the game on every platform).</summary>
    private GameTagEditor TagEditorFor(string key) =>
        new(_saver.Settings.AddedTags.GetValueOrDefault(key) ?? [], tags => OnAddedTagsChanged(key, tags));

    private void OnAddedTagsChanged(string key, IReadOnlyList<int> tags)
    {
        var added = _saver.Settings.AddedTags;
        if (tags.Count == 0)
            added.Remove(key);
        else
            added[key] = [.. tags];
        // Shown at once (under the name, in the "Tags" filter), before the recomputation.
        if (_library.Tags is var (index, names))
            _library.SetTags(index.WithAdded(added), names);
        _choicesChanged();
    }

    private static void SetMembership(HashSet<string> set, string key, bool isMember)
    {
        if (isMember)
            set.Add(key);
        else
            set.Remove(key);
    }

    // ---------- Games added by hand ----------

    /// <summary>The editor of a history line, for a game added by hand.</summary>
    private ManualGameEditor? ManualEditorFor(PlayedGame game) =>
        game.Platform == ManualGames.PlatformName
            && _saver.Settings.ManualGames.FirstOrDefault(g => g.Id == game.PlatformId) is { } manual
            ? new ManualGameEditor(manual, OnManualGameEdited, OnManualGameRemoved)
            : null;

    private void OnManualGameEdited(ManualGame edited)
    {
        var manualGames = _saver.Settings.ManualGames;
        int index = manualGames.FindIndex(g => g.Id == edited.Id);
        if (index < 0)
            return;
        manualGames[index] = edited;
        RefreshRowOf(edited);
        _choicesChanged();
    }

    private void OnManualGameRemoved(ManualGame removed)
    {
        var settings = _saver.Settings;
        settings.ManualGames.RemoveAll(g => g.Id == removed.Id);
        // Its taste choice, if any, goes with it.
        string key = ManualGames.ToPlayed(removed).Key;
        settings.ExcludedFromTaste.Remove(key);
        settings.IncludedInTaste.Remove(key);
        RefreshRowOf(removed);
        HasHistory = _library.HasAnyHistory;
        _choicesChanged();
    }

    /// <summary>
    /// Rebuilds the history line of this game only, at the same place and
    /// still unfolded: rebuilding the whole list would scroll it back to the
    /// top and fold the line being edited. Gone if it was its only platform.
    /// </summary>
    private void RefreshRowOf(ManualGame game)
    {
        string key = ManualGames.ToPlayed(game).Key;
        var old = AllRows.FirstOrDefault(r => r.Details.Any(d => d.Key == key));
        if (old is null)
        {
            Rebuild();
            return;
        }

        // The same game now: the group holding one of the old line's platforms.
        var oldKeys = old.Details.Select(d => d.Key).ToHashSet();
        var group = HistoryMerger.GroupByGame(_library.CombinedHistory()).FirstOrDefault(g => g.Any(p => oldKeys.Contains(p.Key)));
        var fresh = group is null ? null : BuildRow(group, CurrentMatcher(), DateTimeOffset.UtcNow);
        if (fresh is not null)
            fresh.IsExpanded = old.IsExpanded;

        Replace(AllRows, old, fresh);
        Replace(Games, old, fresh);
        UpdateStatus();
        UpdateFilterStatus();
    }

    private static void Replace(IList<GameGroupRow> rows, GameGroupRow old, GameGroupRow? fresh)
    {
        int index = rows.IndexOf(old);
        if (index < 0)
            return;
        if (fresh is null)
            rows.RemoveAt(index);
        else
            rows[index] = fresh;
    }
}
